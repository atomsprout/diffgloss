import type {
  HunkClass,
  ParsedHunk,
  QuestionTrigger,
  RiskLevel,
} from "../schema/types.ts";

export interface ClassificationResult {
  hunkClass: HunkClass;
  classBy: "deterministic";
  reason: string;
  shouldCollapse: boolean;
  risk: RiskLevel;
  trigger?: QuestionTrigger;
  suggestedQuestion?: string;
}

const GENERATED_PATTERNS: RegExp[] = [
  /(^|\/)(package-lock\.json|yarn\.lock|pnpm-lock\.yaml|bun\.lockb?|Cargo\.lock|poetry\.lock|Gemfile\.lock|composer\.lock|go\.sum)$/i,
  /(^|\/)(dist|build|coverage|vendor|node_modules|\.next|out)\//i,
  /\.min\.(js|css)$/i,
  /\.(snap|pb\.go|pb\.ts|generated\.[a-z0-9]+|g\.dart)$/i,
];

const TEST_PATTERNS: RegExp[] = [
  /(^|\/)(__tests__|tests?|spec|e2e)\//i,
  /\.(test|spec)\.[a-z0-9]+$/i,
  /_test\.(go|py|rs)$/i,
];

const CONFIG_PATTERNS: RegExp[] = [
  /(^|\/)\.github\/workflows\/.+\.ya?ml$/i,
  /(^|\/)(Dockerfile|Makefile|Justfile|Procfile)$/i,
  /\.(json|ya?ml|toml|ini|conf|cfg)$/i,
  /(^|\/)\.(gitignore|editorconfig|prettierrc.*|eslintrc.*|npmrc|nvmrc)$/i,
];

const HIGH_RISK_PATH_PATTERNS: RegExp[] = [
  /(auth|session|token|jwt|oauth|rbac|acl|permission|security|crypto|secret|payment|billing|migration|schema)/i,
];

const TEST_ASSERTION_RE =
  /\b(expect|assert|assertEquals|assertStrictEqual|should|toEqual|toBe|toThrow|toHaveBeenCalled|rejects)\b/;

const SAFETY_GUARD_RE =
  /\b(if\s*\(|throw\s+new|return\s+null|return\s+false|authorize|verify|validate|sanitize|checkPermission|requireAuth)\b/;

function isWhitespaceOnlyChange(added: string[], removed: string[]): boolean {
  if (added.length === 0 && removed.length === 0) return false;
  const normAdded = added.map((l) => l.replace(/\s+/g, "")).filter(Boolean);
  const normRemoved = removed.map((l) => l.replace(/\s+/g, "")).filter(Boolean);
  if (normAdded.length !== normRemoved.length) return false;
  return normAdded.every((line, idx) => line === normRemoved[idx]);
}

function isCommentOnlyChange(added: string[], removed: string[]): boolean {
  const all = [...added, ...removed].map((l) => l.trim()).filter(Boolean);
  if (all.length === 0) return false;
  return all.every(
    (l) =>
      l.startsWith("//") ||
      l.startsWith("/*") ||
      l.startsWith("*") ||
      l.startsWith("*/") ||
      l.startsWith("#"),
  );
}

function isPureImportReorder(added: string[], removed: string[]): boolean {
  if (added.length === 0 || added.length !== removed.length) return false;
  const isImport = (line: string) =>
    /^\s*(import\s|from\s+\S+\s+import\s|use\s+\S+;|const\s+.+=\s*require\()/.test(
      line,
    );
  if (!added.every(isImport) || !removed.every(isImport)) return false;
  const sortedAdded = [...added].map((l) => l.trim()).sort();
  const sortedRemoved = [...removed].map((l) => l.trim()).sort();
  return sortedAdded.every((line, idx) => line === sortedRemoved[idx]);
}

function hasGeneratedMarker(patch: string): boolean {
  return /@generated|DO NOT EDIT|auto-generated|Code generated by/i.test(patch);
}

export function classifyHunk(hunk: ParsedHunk): ClassificationResult {
  if (hunk.moved_from) {
    return {
      hunkClass: "moved",
      classBy: "deterministic",
      reason: `Code block moved verbatim from ${hunk.moved_from.path}:${hunk.moved_from.old_range[0]}-${hunk.moved_from.old_range[1]}`,
      shouldCollapse: true,
      risk: "low",
    };
  }

  if (
    hunk.change_type === "renamed" &&
    hunk.added_lines.length === 0 &&
    hunk.removed_lines.length === 0
  ) {
    return {
      hunkClass: "moved",
      classBy: "deterministic",
      reason: `Pure file rename (${hunk.old_path ?? "?"} -> ${hunk.path})`,
      shouldCollapse: true,
      risk: "low",
    };
  }

  if (
    GENERATED_PATTERNS.some((re) => re.test(hunk.path)) ||
    hasGeneratedMarker(hunk.patch)
  ) {
    return {
      hunkClass: "generated",
      classBy: "deterministic",
      reason: "Matched generated/lockfile/vendor rule",
      shouldCollapse: true,
      risk: "low",
    };
  }

  if (isWhitespaceOnlyChange(hunk.added_lines, hunk.removed_lines)) {
    return {
      hunkClass: "mechanical",
      classBy: "deterministic",
      reason: "Whitespace/formatting-only change",
      shouldCollapse: true,
      risk: "low",
    };
  }

  if (isPureImportReorder(hunk.added_lines, hunk.removed_lines)) {
    return {
      hunkClass: "mechanical",
      classBy: "deterministic",
      reason: "Pure import reordering",
      shouldCollapse: true,
      risk: "low",
    };
  }

  if (isCommentOnlyChange(hunk.added_lines, hunk.removed_lines)) {
    return {
      hunkClass: "mechanical",
      classBy: "deterministic",
      reason: "Comment-only edit",
      shouldCollapse: true,
      risk: "low",
    };
  }

  if (TEST_PATTERNS.some((re) => re.test(hunk.path))) {
    const removedAssertions = hunk.removed_lines.filter((l) =>
      TEST_ASSERTION_RE.test(l),
    ).length;
    const addedAssertions = hunk.added_lines.filter((l) =>
      TEST_ASSERTION_RE.test(l),
    ).length;

    if (removedAssertions > 0 && removedAssertions >= addedAssertions) {
      return {
        hunkClass: "test",
        classBy: "deterministic",
        reason: `Test assertions removed or modified (${removedAssertions} removed, ${addedAssertions} added)`,
        shouldCollapse: false,
        risk: "high",
        trigger: "test_assertion_changed",
        suggestedQuestion: `In ${hunk.path} (lines ${hunk.new_range[0]}-${hunk.new_range[1]}), ${removedAssertions} test assertion(s) were removed or altered. What intentional behavior change justifies weakening/changing these assertions, and which test now covers the original invariant?`,
      };
    }

    return {
      hunkClass: "test",
      classBy: "deterministic",
      reason: "Test file change",
      shouldCollapse: false,
      risk: "low",
    };
  }

  if (CONFIG_PATTERNS.some((re) => re.test(hunk.path))) {
    const isCIOrSecurityConfig =
      /\.github\/workflows\/|Dockerfile/i.test(hunk.path);
    return {
      hunkClass: "config",
      classBy: "deterministic",
      reason: isCIOrSecurityConfig
        ? "CI/container configuration change"
        : "Configuration file change",
      shouldCollapse: false,
      risk: isCIOrSecurityConfig ? "medium" : "low",
    };
  }

  // Substantive code change: evaluate deterministic risk hints
  const isSensitivePath = HIGH_RISK_PATH_PATTERNS.some((re) =>
    re.test(hunk.path),
  );
  const removedGuards = hunk.removed_lines.filter((l) =>
    SAFETY_GUARD_RE.test(l),
  ).length;
  const addedGuards = hunk.added_lines.filter((l) =>
    SAFETY_GUARD_RE.test(l),
  ).length;

  if (removedGuards > 0 && addedGuards === 0) {
    return {
      hunkClass: "substantive",
      classBy: "deterministic",
      reason: isSensitivePath
        ? "Sensitive path + guard/check removed"
        : "Conditional guard or error throw removed",
      shouldCollapse: false,
      risk: "high",
      trigger: "safety_check_removed",
      suggestedQuestion: `In ${hunk.path} (lines ${hunk.old_range[0]}-${hunk.old_range[1]}), a guard/validation or throw path was removed without a direct replacement in this hunk. Where is this invariant enforced now?`,
    };
  }

  if (isSensitivePath) {
    return {
      hunkClass: "substantive",
      classBy: "deterministic",
      reason: "Security/auth/data-critical path",
      shouldCollapse: false,
      risk: "high",
      trigger: "no_evidence_for_why",
      suggestedQuestion: `In ${hunk.path} (lines ${hunk.new_range[0]}-${hunk.new_range[1]}), this touches a sensitive path. What concrete requirement or failure mode motivated this change?`,
    };
  }

  const changedCount = hunk.added_lines.length + hunk.removed_lines.length;
  return {
    hunkClass: "substantive",
    classBy: "deterministic",
    reason: "Substantive source change",
    shouldCollapse: false,
    risk: changedCount >= 40 ? "medium" : "low",
  };
}
